import argparse
import fnmatch
import html
import json
import os
import re
import sys
from dataclasses import dataclass
from pathlib import Path, PurePosixPath
from typing import Any, get_args

_REPO_ROOT = Path(__file__).resolve().parents[2]
_DOCS_ROOT = _REPO_ROOT / "docs"
_HOME_NAME = "index.html"
_DOCS_NAME = "docs.html"
_DOCS_OUT = _DOCS_ROOT / _DOCS_NAME
_LLMS_NAME = "llms.txt"
_LLMS_FULL_NAME = "llms-full.txt"
_LINK = re.compile(r"\[[^\]]+\]\(([^)\s]+)")
_HEADING = re.compile(r"^(#{1,6})\s+(.+?)\s*#*\s*$")
_FENCE = re.compile(r"^\s*(```|~~~)")
_INLINE_CODE = re.compile(r"`[^`]*`")
_SCHEMES = ("http://", "https://", "mailto:", "tel:")
_GENERATED_HEADER = (
    "<!-- Generated by `uv run --locked python -m cade.docs catalogs --write`."
    " Do not edit by hand. -->"
)
_GENERATED = {
    "config-catalog": Path("design/config-catalog.md"),
    "event-catalog": Path("design/event-catalog.md"),
    "module-graph": Path("design/module-graph.md"),
}


class DocsError(RuntimeError):
    """文档清单或构建失败。"""


@dataclass(frozen=True)
class Page:
    """一个已发布的文档页。"""

    path: Path
    relative: str
    title: str
    section: str


def load_manifest(root: Path) -> tuple[dict[str, Any], list[str]]:
    """读取 docs.json；返回清单与错误列表。"""
    path = root / "docs.json"
    try:
        raw = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        return {}, [f"{path}: cannot read manifest: {exc}"]
    if not isinstance(raw, dict):
        return {}, [f"{path}: manifest must be a JSON object"]
    errors: list[str] = []
    sections = raw.get("sections")
    if not isinstance(sections, list) or not sections:
        errors.append(f"{path}: sections must be a non-empty list")
        return raw, errors
    seen: set[str] = set()
    for section in sections:
        if not isinstance(section, dict):
            errors.append(f"{path}: section must be an object")
            continue
        title = section.get("title")
        pages = section.get("pages")
        if not isinstance(title, str) or not title.strip():
            errors.append(f"{path}: section title is required")
        if not isinstance(pages, list) or not pages:
            errors.append(f"{path}: section pages must be a non-empty list")
            continue
        for page in pages:
            if not isinstance(page, str) or not page.endswith(".md"):
                errors.append(f"{path}: page must be a .md path: {page!r}")
                continue
            if page in seen:
                errors.append(f"{path}: duplicate page: {page}")
            seen.add(page)
    return raw, errors


def list_pages(root: Path) -> tuple[list[Page], list[str]]:
    """按清单顺序返回页面，并检查缺失、重复和未登记页面。"""
    manifest, errors = load_manifest(root)
    pages: list[Page] = []
    seen: set[str] = set()
    sections = manifest.get("sections", [])
    if not isinstance(sections, list):
        return pages, errors
    for section in sections:
        if not isinstance(section, dict):
            continue
        section_title = str(section.get("title", ""))
        raw_pages = section.get("pages", [])
        if not isinstance(raw_pages, list):
            continue
        for relative in raw_pages:
            if not isinstance(relative, str):
                continue
            path = (root / relative).resolve()
            if not _inside(path, root):
                errors.append(f"{relative}: page escapes docs root")
                continue
            if not path.is_file():
                errors.append(f"{relative}: page does not exist")
                continue
            if relative in seen:
                continue
            seen.add(relative)
            pages.append(
                Page(
                    path=path,
                    relative=relative,
                    title=_title(path),
                    section=section_title,
                )
            )
    excluded = _excluded_patterns(manifest)
    for path in sorted(root.rglob("*.md")):
        relative = path.relative_to(root).as_posix()
        if _excluded(relative, excluded):
            continue
        if relative not in seen:
            errors.append(f"{relative}: markdown file is not listed in docs.json")
    return pages, errors


def check(root: Path = _DOCS_ROOT) -> list[str]:
    """检查根目录及其直接子目录中每个清单的一致性。"""
    errors: list[str] = []
    for manifest_root in _manifest_roots(root):
        prefix = (
            ""
            if manifest_root == root
            else f"{manifest_root.relative_to(root).as_posix()}/"
        )
        errors.extend(f"{prefix}{item}" for item in _check_root(manifest_root))
    return errors


def _manifest_roots(root: Path) -> list[Path]:
    """返回根目录和带独立清单的直接子目录。"""
    roots = [root]
    for child in sorted(root.iterdir()):
        if child.is_dir() and (child / "docs.json").is_file():
            roots.append(child)
    return roots


def _check_root(root: Path) -> list[str]:
    """检查单个清单的页面、链接、锚点和生成物。"""
    pages, errors = list_pages(root)
    anchors: dict[str, set[str]] = {}
    for page in pages:
        headings, heading_errors = _headings(page.path)
        anchors[page.relative] = headings
        errors.extend(f"{page.relative}: {message}" for message in heading_errors)
    for page in pages:
        for line, target in _links(page.path):
            errors.extend(
                _check_link(
                    root,
                    page,
                    target,
                    anchors,
                    line,
                )
            )
    if errors:
        return errors
    expected = render_llms(root)
    llms_path = root / _LLMS_NAME
    if not llms_path.is_file():
        errors.append(f"{_LLMS_NAME}: generated catalog is missing")
    else:
        actual = llms_path.read_text(encoding="utf-8")
        if actual != expected:
            errors.append(
                f"{_LLMS_NAME}: out of date; run `python -m cade.docs llms --write`"
            )
    full_expected = render_llms_full(root)
    full_path = root / _LLMS_FULL_NAME
    if not full_path.is_file():
        errors.append(f"{_LLMS_FULL_NAME}: generated catalog is missing")
    else:
        actual_full = full_path.read_text(encoding="utf-8")
        if actual_full != full_expected:
            errors.append(
                f"{_LLMS_FULL_NAME}: out of date; run "
                "`python -m cade.docs llms --write`"
            )
    for relative, expected in catalog_files().items():
        path = root / relative
        if not path.is_file():
            errors.append(f"{relative}: generated catalog is missing")
        elif path.read_text(encoding="utf-8") != expected:
            errors.append(
                f"{relative}: out of date; run `python -m cade.docs catalogs --write`"
            )
    return errors


def render_llms(root: Path = _DOCS_ROOT) -> str:
    """生成 llms.txt 目录。"""
    manifest, errors = load_manifest(root)
    if errors:
        raise DocsError("; ".join(errors))
    lines = [
        f"# {manifest.get('title', 'Cade')}",
        "",
        f"> {manifest.get('description', '')}",
        "",
    ]
    sections = manifest.get("sections", [])
    if isinstance(sections, list):
        for section in sections:
            if not isinstance(section, dict):
                continue
            title = str(section.get("title", ""))
            pages = section.get("pages", [])
            if not isinstance(pages, list):
                continue
            lines.append(f"## {title}")
            for relative in pages:
                if not isinstance(relative, str):
                    continue
                path = root / relative
                lines.append(f"- [{_title(path)}]({relative})")
            lines.append("")
    return "\n".join(lines)


def render_llms_full(root: Path = _DOCS_ROOT) -> str:
    """生成包含完整页面正文的 llms-full.txt。"""
    manifest, manifest_errors = load_manifest(root)
    if manifest_errors:
        raise DocsError("; ".join(manifest_errors))
    pages, page_errors = list_pages(root)
    if page_errors:
        raise DocsError("; ".join(page_errors))
    lines = [
        f"# {manifest.get('title', 'Cade')}",
        "",
        f"> {manifest.get('description', '')}",
        "",
    ]
    for page in pages:
        lines.extend(
            [
                f"# {page.title}",
                "",
                f"<!-- source: {page.relative} -->",
                "",
                page.path.read_text(encoding="utf-8").strip(),
                "",
            ]
        )
    return "\n".join(lines)


def write_llms(root: Path = _DOCS_ROOT) -> Path:
    """把生成结果写入 llms.txt 和 llms-full.txt。"""
    path = root / _LLMS_NAME
    path.write_text(render_llms(root), encoding="utf-8")
    full_path = root / _LLMS_FULL_NAME
    full_path.write_text(render_llms_full(root), encoding="utf-8")
    return path


def catalog_files() -> dict[str, str]:
    """生成配置、事件和模块图目录。"""
    return {
        _GENERATED["config-catalog"].as_posix(): render_config_catalog(),
        _GENERATED["event-catalog"].as_posix(): render_event_catalog(),
        _GENERATED["module-graph"].as_posix(): render_module_graph(),
    }


def write_catalogs(root: Path = _DOCS_ROOT) -> list[Path]:
    """写入生成的目录页面。"""
    paths: list[Path] = []
    for relative, content in catalog_files().items():
        path = root / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        paths.append(path)
    return paths


def render_config_catalog() -> str:
    """从 CadeConfig 生成配置字段目录。"""
    from cade.app.config import CadeConfig

    schema = CadeConfig.model_json_schema()
    properties = schema.get("properties", {})
    lines = [
        _GENERATED_HEADER,
        "",
        "# Configuration catalog",
        "",
        "Top-level fields. Nested types follow the table.",
        "",
        "| Field | Type | Default |",
        "| --- | --- | --- |",
    ]
    for name, prop in properties.items():
        if not isinstance(prop, dict):
            continue
        lines.append(
            f"| `{name}` | `{_cell(_type_label(prop))}` | `{_default_label(prop)}` |"
        )
    definitions = schema.get("$defs", {})
    if isinstance(definitions, dict):
        for name, definition in definitions.items():
            if not isinstance(definition, dict):
                continue
            nested = definition.get("properties", {})
            if not isinstance(nested, dict) or not nested:
                continue
            lines.extend(
                [
                    "",
                    f"## {name}",
                    "",
                    "| Field | Type | Default |",
                    "| --- | --- | --- |",
                ]
            )
            for field, prop in nested.items():
                if isinstance(prop, dict):
                    lines.append(
                        f"| `{field}` | `{_cell(_type_label(prop))}` | "
                        f"`{_default_label(prop)}` |"
                    )
    lines.append("")
    return "\n".join(lines)


def render_event_catalog() -> str:
    """从 EventType 生成会话事件目录。"""
    from cade.harness.session.types import EventType

    purposes = {
        "meta": ("No", "Session creation"),
        "system": ("Yes", "Base system prompt; latest wins"),
        "user": ("Yes", "Task or steering input"),
        "assistant": ("Yes", "Model text and tool calls"),
        "tool_result": ("Yes", "Tool output paired by call ID"),
        "tool_execution": ("No", "Nested tool dispatch and outcome"),
        "compaction": ("Yes", "Summary and first kept entry"),
        "window": ("Yes", "Context start and optional handoff"),
        "request": ("No", "Provider request audit"),
        "run": ("No", "Run termination, steps, and usage"),
        "attempt": ("No", "Provider attempt, retry, or failure"),
    }
    lines = [
        _GENERATED_HEADER,
        "",
        "# Event catalog",
        "",
        "Session entry types from `EventType`.",
        "",
        "| Event | Projects | Purpose |",
        "| --- | --- | --- |",
    ]
    alias = getattr(EventType, "__value__", EventType)
    for event in get_args(alias):
        projects, purpose = purposes.get(str(event), ("No", "Unclassified"))
        lines.append(f"| `{event}` | {projects} | {purpose} |")
    lines.append("")
    return "\n".join(lines)


def render_module_graph() -> str:
    """按 Cade 包内的绝对导入生成模块图。"""
    package = Path(__file__).resolve().parent
    edges: set[tuple[str, str]] = set()
    for path in sorted(package.rglob("*.py")):
        if path.name == "__init__.py":
            continue
        relative = path.relative_to(package).with_suffix("")
        source = ".".join(relative.parts)
        if source == "docs":
            continue
        text = path.read_text(encoding="utf-8")
        for match in re.finditer(
            r"^from cade\.([\w.]+) import",
            text,
            re.MULTILINE,
        ):
            target = match.group(1)
            if target != source:
                edges.add((source, target))
    lines = [
        _GENERATED_HEADER,
        "",
        "# Module graph",
        "",
        "Absolute imports inside `src/cade/`.",
        "",
        "```mermaid",
        "flowchart LR",
    ]
    for source, target in sorted(edges):
        lines.append(f"  {_node(source)} --> {_node(target)}")
    lines.extend(["```", ""])
    return "\n".join(lines)


def _node(module: str) -> str:
    return module.replace(".", "_")


def _type_label(prop: dict[str, Any]) -> str:
    ref = prop.get("$ref")
    if isinstance(ref, str):
        return ref.rsplit("/", 1)[-1]
    options = prop.get("anyOf")
    if isinstance(options, list):
        labels: list[str] = []
        nullable = False
        for option in options:
            if not isinstance(option, dict):
                continue
            if option.get("type") == "null":
                nullable = True
                continue
            labels.append(_type_label(option))
        label = " | ".join(dict.fromkeys(labels))
        return f"{label} | null" if nullable and label else "null"
    enum = prop.get("enum")
    if isinstance(enum, list):
        return " | ".join(str(item) for item in enum)
    kind = prop.get("type")
    if kind == "array":
        items = prop.get("items")
        return f"list[{_type_label(items) if isinstance(items, dict) else 'any'}]"
    if kind == "object":
        additional = prop.get("additionalProperties")
        if isinstance(additional, dict):
            return f"dict[str, {_type_label(additional)}]"
        return "object"
    return str(kind or "any")


def _default_label(prop: dict[str, Any]) -> str:
    if "default" not in prop:
        return "required"
    return json.dumps(prop["default"], ensure_ascii=False).replace("|", "\\|")


def _cell(value: str) -> str:
    return value.replace("|", "\\|")


def _alternate_link(manifest: dict[str, Any], page_name: str) -> str:
    """生成页头中指向另一语言对应页面的链接。"""
    alternate = manifest.get("alternate")
    if not isinstance(alternate, dict):
        return ""
    label = alternate.get("label")
    href = alternate.get("href")
    if not isinstance(label, str) or not isinstance(href, str):
        return ""
    if not label or not href:
        return ""
    try:
        target = PurePosixPath(href).with_name(page_name)
    except ValueError:
        return ""
    return (
        f'<a class="lang" href="{html.escape(str(target), quote=True)}">'
        f"{html.escape(label)}</a>"
    )


def _brand(manifest: dict[str, Any]) -> str:
    """返回站点品牌名，未设置时使用标题。"""
    brand = manifest.get("brand")
    if isinstance(brand, str) and brand.strip():
        return brand
    return str(manifest.get("title", "Cade"))


def _relative_link(target: Path, start: Path) -> str:
    """返回两个站内路径之间的 POSIX 相对链接。"""
    return Path(os.path.relpath(target, start)).as_posix()


def _render_docs(root: Path, out: Path) -> Path:
    """把清单中的页面渲染到独立文档页。"""
    try:
        from markdown_it import MarkdownIt
    except ImportError as exc:
        raise DocsError(
            "build requires markdown-it-py; install the docs extra"
        ) from exc
    pages, errors = list_pages(root)
    if errors:
        raise DocsError("; ".join(errors))
    renderer = MarkdownIt("gfm-like", {"html": False, "linkify": False})
    page_ids = {page.path.resolve(): _slug(page.path.stem) for page in pages}
    sections: list[str] = []
    for page in pages:
        body = renderer.render(page.path.read_text(encoding="utf-8"))
        body = _rewrite_internal_links(body, page_ids, page.path.parent, out.parent)
        sections.append(
            f'<section class="page" id="page-{page_ids[page.path.resolve()]}" '
            f'data-title="{html.escape(page.title)}">\n'
            f"{body}\n"
            "</section>"
        )
    sidebar: list[str] = []
    current_section = ""
    for page in pages:
        if page.section != current_section:
            if current_section:
                sidebar.append("</div>")
            sidebar.append(f'<div class="nav-group"><p>{html.escape(page.section)}</p>')
            current_section = page.section
        sidebar.append(
            f'<a href="#page-{_slug(page.path.stem)}">{html.escape(page.title)}</a>'
        )
    if current_section:
        sidebar.append("</div>")
    manifest, manifest_errors = load_manifest(root)
    if manifest_errors:
        raise DocsError("; ".join(manifest_errors))
    home_out = out.with_name(_HOME_NAME)
    document = _DOCS_TEMPLATE.replace("__STYLE__", _STYLE)
    document = document.replace("__THEME_BOOT__", _THEME_BOOT)
    document = document.replace(
        "__LANG__", html.escape(str(manifest.get("lang") or "en"))
    )
    document = document.replace(
        "__TITLE__", html.escape(str(manifest.get("title", "Cade")))
    )
    document = document.replace(
        "__DESCRIPTION__", html.escape(str(manifest.get("description", "")))
    )
    document = document.replace("__BRAND__", html.escape(_brand(manifest)))
    document = document.replace(
        "__HOME_HREF__", html.escape(_relative_link(home_out, out.parent), quote=True)
    )
    document = document.replace("__ALTERNATE__", _alternate_link(manifest, out.name))
    document = document.replace("__NAV__", "\n".join(sidebar))
    document = document.replace("__CONTENT__", "\n".join(sections))
    document = document.replace("__SCRIPTS__", f"{_COMMON_SCRIPT}\n{_DOCS_SCRIPT}")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(document, encoding="utf-8")
    return out


def build(root: Path = _DOCS_ROOT, out: Path = _DOCS_OUT) -> Path:
    """渲染独立文档页；主页由仓库中的静态页面维护。"""
    return _render_docs(root, out)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="cade-docs")
    parser.add_argument("--root", type=Path, default=_DOCS_ROOT)
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("check", help="Validate manifest, links, and llms.txt")
    build_parser = sub.add_parser("build", help="Render the documentation page")
    build_parser.add_argument("--out", type=Path, default=_DOCS_OUT)
    llms_parser = sub.add_parser("llms", help="Print or write llms.txt")
    llms_parser.add_argument("--write", action="store_true")
    catalogs_parser = sub.add_parser(
        "catalogs",
        help="Print or write generated catalogs",
    )
    catalogs_parser.add_argument("--write", action="store_true")
    args = parser.parse_args(argv)

    if args.command == "check":
        issues = check(args.root)
        if issues:
            for issue in issues:
                print(f"docs: {issue}", file=sys.stderr)
            print(f"docs check failed: {len(issues)} issue(s)", file=sys.stderr)
            return 1
        print("docs check passed")
        return 0
    if args.command == "build":
        try:
            path = build(args.root, args.out)
        except DocsError as exc:
            print(f"docs: {exc}", file=sys.stderr)
            return 1
        print(path)
        return 0
    if args.command == "llms":
        if args.write:
            print(write_llms(args.root))
        else:
            print(render_llms(args.root), end="")
        return 0
    if args.command == "catalogs":
        if args.write:
            for path in write_catalogs(args.root):
                print(path)
        else:
            for relative in catalog_files():
                print(relative)
        return 0
    return 2


def _title(path: Path) -> str:
    try:
        text = path.read_text(encoding="utf-8")
    except OSError:
        return path.stem
    for line in text.splitlines():
        match = _HEADING.match(line)
        if match and len(match.group(1)) == 1:
            return _plain(match.group(2))
    return path.stem


def _plain(text: str) -> str:
    text = re.sub(r"`([^`]*)`", r"\1", text)
    text = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", text)
    text = re.sub(r"[*_~]", "", text)
    return " ".join(text.split())


def _headings(path: Path) -> tuple[set[str], list[str]]:
    anchors: set[str] = set()
    errors: list[str] = []
    fence = ""
    for number, line in enumerate(
        path.read_text(encoding="utf-8").splitlines(),
        start=1,
    ):
        marker = _FENCE.match(line)
        if marker:
            fence = "" if fence == marker.group(1) else marker.group(1)
            continue
        if fence:
            continue
        match = _HEADING.match(line)
        if not match:
            continue
        slug = _slug(match.group(2))
        if slug in anchors:
            errors.append(f"line {number}: duplicate heading anchor #{slug}")
        anchors.add(slug)
    return anchors, errors


def _links(path: Path) -> list[tuple[int, str]]:
    result: list[tuple[int, str]] = []
    fence = ""
    for number, line in enumerate(
        path.read_text(encoding="utf-8").splitlines(),
        start=1,
    ):
        marker = _FENCE.match(line)
        if marker:
            fence = "" if fence == marker.group(1) else marker.group(1)
            continue
        if fence:
            continue
        cleaned = _INLINE_CODE.sub("", line)
        for match in _LINK.finditer(cleaned):
            result.append((number, match.group(1)))
    return result


def _check_link(
    root: Path,
    page: Page,
    target: str,
    anchors: dict[str, set[str]],
    line: int,
) -> list[str]:
    if target.startswith(_SCHEMES):
        return []
    path_part, _, anchor = target.partition("#")
    if not path_part:
        if anchor and anchor not in anchors.get(page.relative, set()):
            return [f"{page.relative}:{line}: unknown anchor #{anchor}"]
        return []
    resolved = (page.path.parent / path_part).resolve()
    if not resolved.exists():
        return [f"{page.relative}:{line}: missing link target: {path_part}"]
    if anchor and resolved.suffix == ".md":
        try:
            relative = resolved.relative_to(root.resolve()).as_posix()
        except ValueError:
            relative = ""
        known = anchors.get(relative)
        if known is not None and anchor not in known:
            return [f"{page.relative}:{line}: unknown anchor #{anchor} in {relative}"]
    return []


def _rewrite_internal_links(
    body: str,
    page_ids: dict[Path, str],
    source_dir: Path,
    output_dir: Path,
) -> str:
    def replace(match: re.Match[str]) -> str:
        target = html.unescape(match.group(1))
        if target.startswith((*_SCHEMES, "#", "/")):
            return match.group(0)
        path_part, separator, anchor = target.partition("#")
        resolved = (source_dir / path_part).resolve()
        if page_id := page_ids.get(resolved):
            return f'href="#page-{page_id}"'
        relative = Path(os.path.relpath(resolved, output_dir)).as_posix()
        return f'href="{html.escape(relative + separator + anchor, quote=True)}"'

    return re.sub(r'href="([^"]+)"', replace, body)


def _excluded_patterns(manifest: dict[str, Any]) -> list[str]:
    raw = manifest.get("exclude", [])
    if not isinstance(raw, list):
        return []
    return [item for item in raw if isinstance(item, str)]


def _excluded(relative: str, patterns: list[str]) -> bool:
    return any(fnmatch.fnmatch(relative, pattern) for pattern in patterns)


def _slug(value: str) -> str:
    text = _plain(value).lower()
    text = re.sub(r"[^\w\s-]", "", text, flags=re.UNICODE)
    text = re.sub(r"[\s_]+", "-", text).strip("-")
    return text or "section"


def _inside(path: Path, root: Path) -> bool:
    try:
        path.relative_to(root.resolve())
    except ValueError:
        return False
    return True


